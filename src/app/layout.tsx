import { Metadata } from "next";
import { cookies } from "next/headers";
import React, { Suspense } from "react";
import { Refine } from "@refinedev/core";
import { DevtoolsProvider } from "@providers/devtools";
import { RefineKbar, RefineKbarProvider } from "@refinedev/kbar";
import { useNotificationProvider, RefineSnackbarProvider } from "@refinedev/mui";
import routerProvider from "@refinedev/nextjs-router";

import { authProviderClient } from "@providers/auth-provider/auth-provider.client";
import { dataProvider } from "@providers/data-provider";
import { accessControlProvider } from "@providers/access-control";
import { ColorModeContextProvider } from "@contexts/color-mode";
import { UserContextProvider } from "@contexts/user";

export const metadata: Metadata = {
	title: "Refine",
	description: "Generated by create refine app",
	icons: {
		icon: "/favicon.ico",
	},
};

export default async function RootLayout({
	children,
}: Readonly<{
	children: React.ReactNode;
}>) {
	const cookieStore = await cookies();
	const theme = cookieStore.get("theme");
	const defaultMode = theme?.value === "dark" ? "dark" : "light";

	return (
		<html lang="en">
			<body>
				<Suspense>
					<RefineKbarProvider>
						<ColorModeContextProvider defaultMode={defaultMode}>
							<RefineSnackbarProvider>
								<DevtoolsProvider>
									<Refine
										routerProvider={routerProvider}
										authProvider={authProviderClient}
										dataProvider={dataProvider}
										notificationProvider={useNotificationProvider}
										accessControlProvider={accessControlProvider}
                                        resources={[
                                            {
                                                name: "applicants",
                                                list: "/applicants",
                                                create: "/applicants/create",
                                                edit: "/applicants/edit/:id",
                                                show: "/applicants/show/:id",
                                            },
                                            {
                                                name: "interviews",
                                                list: "/interviews",
                                                create: "/interviews/create",
                                                edit: "/interviews/edit/:id",
                                                show: "/interviews/show/:id",
                                            },
                                        ]}
										options={{
											syncWithLocation: true,
											warnWhenUnsavedChanges: true,
											projectId: "u41kJ3-CtoUF1-aJa50m",
											title: {
												text: "Tidewrk-Test",
											},
										}}
									>
										<UserContextProvider>
											{children}
										</UserContextProvider>
										<RefineKbar />
									</Refine>
								</DevtoolsProvider>
							</RefineSnackbarProvider>
						</ColorModeContextProvider>
					</RefineKbarProvider>
				</Suspense>
			</body>
		</html>
	);
}
